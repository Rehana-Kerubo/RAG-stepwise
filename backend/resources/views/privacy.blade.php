    <h1 class="mt-4 text-[30px] font-extrabold tracking-tight">Privacy policy</h1>
    <p class="mt-1 text-sm text-[#5B6070]">Last updated 27 October 2026</p>

    <p class="mt-5">
        StepWise guides sales agents through onboarding steps for clients such as Safaricom and Airtel.
        This page explains what the app collects, why, and who can see it.
    </p>

    <h2 class="mt-7 text-lg font-bold">What we collect</h2>
    <p class="mt-2">From your Google account: your name, email address and profile photo.</p>
    <p class="mt-2">From you: your phone number and region.</p>
    <p class="mt-2">
        While you onboard a customer: the photos, codes and answers you submit at each step. This can include
        photos of ID documents and shopfronts that belong to the customer.
    </p>
    <p class="mt-2">The questions you ask the StepWise assistant, and the answers it gives.</p>

    <h2 class="mt-7 text-lg font-bold">Why we collect it</h2>
    <p class="mt-2">
        To sign you in, to record your onboarding progress, to let managers see where agents need help,
        and to improve the guidance on steps that many agents find hard.
    </p>

    <h2 class="mt-7 text-lg font-bold">Who can see it</h2>
    <p class="mt-2">
        Managers can see your onboardings, your progress and the questions you asked the assistant.
        Photos and codes are not shown in the manager screens. They are stored privately on the
        StepWise server.
    </p>
    <p class="mt-2">
        The assistant runs on StepWise's own server. Your photos, ID numbers and activation codes are
        never sent to it, only your question and the text of the step you are on.
    </p>
    <p class="mt-2">We do not sell your data or share it with advertisers.</p>

    <h2 class="mt-7 text-lg font-bold">Your camera</h2>
    <p class="mt-2">
        StepWise asks for camera access only so you can take photos for onboarding steps. You can turn
        it off at any time in your phone settings.
    </p>

    <h2 class="mt-7 text-lg font-bold">Customer photos and consent</h2>
    <p class="mt-2">
        The photos you take belong to the customer you are onboarding. Only photograph a person's
        documents or premises with their permission, and only for the onboarding you are doing.
    </p>

    <h2 class="mt-7 text-lg font-bold">How long we keep it</h2>
    <p class="mt-2">
        Your data is kept while your agent account is active. You can ask us to delete it at any time
        using the email below.
    </p>

    <h2 class="mt-7 text-lg font-bold">Your rights</h2>
    <p class="mt-2">
        You can ask to see the data we hold about you, to correct it, or to have it deleted.
        This follows Kenya's Data Protection Act, 2019.
    </p>

